import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const root = path.resolve(path.dirname(scriptPath), "..");
const assets = path.join(root, "skills", "han-design", "assets");
export const scopedCssBanner = "/* Generated by scripts/generate-scoped-css.mjs. Do not edit directly. */\n";

function read(name) {
  return fs.readFileSync(path.join(assets, name), "utf8");
}

function write(name, source) {
  fs.writeFileSync(path.join(assets, name), scopedCssBanner + source);
}

function scopeDataSelectors(source) {
  return source.replace(
    /^\[data-(theme|color-mode)=(['"][^'"]+['"])\]/gm,
    (_, attribute, value) =>
      `:where([data-han-scope][data-${attribute}=${value}], [data-han-scope] [data-${attribute}=${value}])`,
  );
}

export function buildScopedCss() {
  const tokens = scopeDataSelectors(read("tokens.css")).replace(/^:root\s*\{/m, "[data-han-scope] {");
  const themes = ["themes.css", "palettes.css"]
    .map((name) => scopeDataSelectors(read(name)))
    .join("\n\n");
  const accessibility = read("accessibility.css").replaceAll(
    ":where([data-theme])",
    ":where([data-han-scope])",
  );
  return {
    "tokens-scoped.css": scopedCssBanner + tokens,
    "themes-scoped.css": scopedCssBanner + themes,
    "accessibility-scoped.css": scopedCssBanner + accessibility,
  };
}

export function generateScopedCss() {
  for (const [name, source] of Object.entries(buildScopedCss())) {
    fs.writeFileSync(path.join(assets, name), source);
  }
}

if (path.resolve(process.argv[1] ?? "") === scriptPath) {
  generateScopedCss();
  console.log("Generated scoped token, theme, and accessibility stylesheets");
}
